// Keeps docs/overview.html, the plain-language page for humans, honest about the ADRs.
//
// The ADRs under docs/adr/ are the canonical record, written for agents; the overview
// is derived from them by hand. docs/overview.sources holds a hash of each ADR as it
// stood when the page was last brought up to date, so changing an ADR without
// revisiting the page fails here instead of leaving the page quietly wrong. Stamping
// also embeds every ADR's text in the page, between the records markers, so its "Full
// record" links show the Markdown formatted even when the page is opened from disk,
// where a browser will not fetch the .md files.
//
//   pnpm docs:check   # CI: fail if an ADR changed since the last stamp
//   pnpm docs:stamp   # after updating the overview page and docs/README.md
//
// Deliberately not part of build:deploy: a stale summary must never block a deploy.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DOCS = join(import.meta.dirname, "..", "docs");
const PAGE = join(DOCS, "overview.html");
const SOURCES = join(DOCS, "overview.sources");
const START = "<!-- records:start";
const END = "<!-- records:end -->";

/** Every ADR except the template, relative to docs/. A new ADR is picked up by the glob. */
function records() {
  return readdirSync(join(DOCS, "adr"))
    .filter((name) => /^\d{4}-.*\.md$/.test(name) && !name.startsWith("0000-"))
    .sort()
    .map((name) => `adr/${name}`);
}

/** Line endings normalised, so a CRLF Windows checkout and CI's LF agree. */
const read = (rel) => readFileSync(join(DOCS, rel), "utf8").replace(/\r\n/g, "\n");

const digest = (rel) => createHash("sha256").update(read(rel)).digest("hex").slice(0, 16);

function stamp() {
  const rels = records();
  const html = readFileSync(PAGE, "utf8");
  const pattern = new RegExp(`${escape(START)}[\\s\\S]*?${escape(END)}`);
  if (!pattern.test(html)) {
    console.error(`overview.html has no ${START} ... ${END} markers; nothing stamped.`);
    return 1;
  }

  // Every "<" escaped, so a "</script>" inside an ADR cannot end the element early.
  const data = JSON.stringify(Object.fromEntries(rels.map((rel) => [rel, read(rel)]))).replace(
    /</g,
    "\\u003c",
  );
  const block =
    `${START} -- generated by \`pnpm docs:stamp\`; do not edit -->\n` +
    `<script type="application/json" id="records">${data}</script>\n${END}`;
  writeFileSync(
    PAGE,
    html.replace(pattern, () => block),
  );

  const header =
    "# Hashes of the ADRs docs/overview.html was last updated against.\n" +
    "# Regenerate with `pnpm docs:stamp`, and only after updating the page\n" +
    "# and docs/README.md to match.\n";
  writeFileSync(SOURCES, header + rels.map((rel) => `${digest(rel)}  ${rel}`).join("\n") + "\n");
  console.log(`stamped ${rels.length} ADRs into overview.sources and overview.html`);
  return 0;
}

function check() {
  let recorded;
  try {
    recorded = new Map(
      readFileSync(SOURCES, "utf8")
        .split(/\r?\n/)
        .filter((line) => line.trim() && !line.startsWith("#"))
        .map((line) => line.split(/\s+/).reverse()),
    );
  } catch {
    console.error("docs/overview.sources is missing: run `pnpm docs:stamp`.");
    return 1;
  }

  const stale = records().filter((rel) => recorded.get(rel) !== digest(rel));
  if (stale.length === 0) {
    console.log("ok: docs/overview.html is current with every ADR");
    return 0;
  }
  console.error(
    `docs/overview.html is out of date with: ${stale.join(", ")}.\n` +
      "  Update the page and the matching docs/README.md row, then run `pnpm docs:stamp`.",
  );
  return 1;
}

function escape(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

process.exit(process.argv[2] === "--stamp" ? stamp() : check());
